const model = (cells, layers = '<mxCell id="1" parent="0"/>') => `<mxGraphModel dx="800" dy="600" grid="1"><root><mxCell id="0"/>${layers}${cells}</root></mxGraphModel>`;
const compress = (xml) => zlib.deflateRawSync(Buffer.from(encodeURIComponent(xml))).toString("base64");
const file = (pages) => `<mxfile host="s1-fixtures">${pages.map(([n, body]) => `<diagram id="${n}" name="${n}">${body}</diagram>`).join("")}</mxfile>`;
